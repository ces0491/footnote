import { connection } from "next/server";
import { Suspense } from "react";

import { StartReplay } from "@/components/start-replay";
import { Card, CardContent, CardDescription, CardHeader, CardTitle } from "@/components/ui/card";
import { Skeleton } from "@/components/ui/skeleton";
import type { MatchMeta } from "@/lib/live/contract";
import { db } from "@/lib/server/db";

async function MatchOnOffer() {
  await connection();
  let match: MatchMeta | undefined;
  try {
    const { rows } = await db().query("select meta from matches order by updated_at desc limit 1");
    match = rows[0]?.meta;
  } catch (error) {
    console.error("loading the match failed", error);
  }
  if (!match) return <CardTitle>The showcase match</CardTitle>;
  return (
    <>
      <CardTitle className="flex flex-wrap items-center gap-2 text-xl">
        <span aria-hidden className="size-3 rounded-full" style={{ background: match.home.colours[0] }} />
        {match.home.name}
        <span className="text-muted-foreground">v</span>
        <span aria-hidden className="size-3 rounded-full" style={{ background: match.away.colours[0] }} />
        {match.away.name}
      </CardTitle>
      <CardDescription>
        {match.competition} {match.season} · {match.venue} · Referee {match.referee.name}
      </CardDescription>
    </>
  );
}

export default function Home() {
  return (
    <main className="mx-auto w-full max-w-3xl flex-1 space-y-8 px-4 py-10 sm:py-16">
      <header className="space-y-2">
        <h1 className="text-3xl font-bold tracking-tight">Footnote</h1>
        <p className="text-muted-foreground">
          Explained match intelligence from synthetic football events. Replay the showcase match and watch the
          live stats follow the feed through Azure Event Hubs, the stream processor and Web PubSub.
        </p>
      </header>
      <Card>
        <CardHeader>
          <Suspense fallback={<Skeleton className="h-7 w-80" />}>
            <MatchOnOffer />
          </Suspense>
        </CardHeader>
        <CardContent>
          <StartReplay />
        </CardContent>
      </Card>
      <p className="text-xs text-muted-foreground">
        Everything here is synthetic: the league, clubs, players, officials and matches are generated by code. No
        real match data, footage, clubs, players or crests are used.
      </p>
    </main>
  );
}
